                      <td>
                        <p><strong>The Context:</strong></p>
                      </td>
                      <td>
                        <ul class="list-style-7-unbold margin-30px-bottom">
                          <li>Rudraksha is a “wonder bead” with huge medicinal and holistic properties. According to
                            ancient literature (Vedas and Purans) Rudraksha means tears of ‘Lord Shiva’ (‘Rudra’ means
                            ‘Shiva’ and ‘aksh’ means ‘tear’) and botanically it’s a fruit having botanical name of
                            Elaeocarpus sp. Large number of pharmacological properties, compositional characteristics,
                            and electromagnetic activities in traditional literature have been mentioned but without any
                            scientific evidences. Hence, the University established “Centre for Research on Rudraksha”
                            for scientific research to prove its medicinal and other qualities.</li>
                          <li>There is a dichotomy between western and Indian beliefs where western mind believes in a
                            targeted approach while Indian tradition believes in holistic approach for well-being. </li>
                          <li>Inadequate and insufficient documentation poses restrictions in the adoption of
                            traditional medicine.</li>
                          <li>Multi-cultural existence or religious factors affect the use as Rudraksha being considered
                            as symbol of Hindu mythology.</li>
                          <li>Diminishing biodiversity and a general belief in the society that it can be cultivated
                            only in hilly areas.</li>
                        </ul>
                      </td>
                    </tr>
                    <tr class="active">
                      <td>
                        <p><strong>The Practice:</strong></p>
                      </td>
                      <td>
                        <p><strong>Practice and Its Uniqueness:</strong></p>
                        <p>SIET is actively involved in the global awareness, advocacy, and promotion of research and
                          mass plantation of Rudraksha, since more than ten years. CeRR is working on different domains
                          of research on Rudraksha including but not limited to scientific validation of its medicinal
                          properties; molecular mechanism of action; structural, compositional, and phytochemical
                          characterization; development of chemical and molecular markers; tissue culture propagation
                          for mass production; mass plantation of Rudraksha; innovative product development from
                          Rudraksha with biomaterials, therapeutic and nutraceutical values using nanotechnology and
                          other tools. At SIET, two doctoral research works have already been successfully conducted
                          with international impact, several research scholars are actively pursuing their research work
                          on different domains of Rudraksha.</p>
                        <p>Thus, the Centre for Research of Rudraksha (CeRR) is one of its kind at national and
                          international platform with the vision to serve the community as a major Resource Centre for
                          the development of innovative technologies and products using Rudraksha for the overall
                          wellbeing and building of healthy society.</p>
                      </td>
                    </tr>
                    <tr class="active">
                      <td>
                        <p><strong>Evidence of Success</strong></p>
                      </td>
                      <td>
                        <ul class="list-style-7-unbold margin-30px-bottom">
                          <li>The Center has been highly successful in its objectives. Two doctoral thesis have already
                            been completed, others are working. </li>
                          <li>08 original research papers related to Rudraksha have already been published and others
                            are under publication.</li>
                          <li>MoU have been signed with start-up company Aanandit Rudraksham Pvt Ltd for commercial
                            development of wearable product of Rudraksha for promoting health &amp; well-being.</li>
                          <li>For this purpose skill based training programs have been conducted to train entrepreneurs
                            wishing to enter into commercial production of Rudraksha based products.</li>
                          <li>Self Help Groups (SHG) have been formed for providing skills and employment to nearby
                            rural population of Meerut.</li>
                          <li>Thousands of plants of Rudraksha have been planted at various locations in India for which
                            the plantlets were raised at SIET campus through grafting from large number of growing
                            trees.</li>
                          <li>We have found that Rudraksha is flowering and fruiting in sub-tropical, non-hilly climate
                            like Meerut.</li>

                        </ul>
                      </td>
