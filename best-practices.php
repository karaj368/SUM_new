                        <p><strong>Challenging Issues – Problems encountered.</strong></p>
                      </td>
                      <td>
                        <ul class="list-style-7-unbold margin-30px-bottom">
                          <li>One of the biggest challenge is to change the mindset of the research communities
                            specially of western researchers. For them Rudraksha is just another plant and it is
                            difficult for them to accept its holistic and medicinal benefits.</li>
                          <li>There is widespread unawareness about the potential of Rudraksha as promising and unique
                            material with great scope for development of innovative solutions. For instance- Rudraksha
                            is an intrinsic electromagnetic bead which can be effectively used to protect from the
                            ever-rising electromagnetic pollution. </li>
                          <li>Development of effective prototypes needs huge investment in term of finance. Hence,
                            getting funding is one of the greatest challenge.</li>
                          <li>For large scale project Government support is desirable. However, getting this is a
                            further challenge.</li>
                        </ul>
