                        <p>In accordance with the vision of Honorable The Prime Minister of India, Shri Narendra Modi,
                          SIET is working on Rudraksha, a symbol of rich, diverse, and ancient knowledge systems and
                          traditions. Rudraksha means tears of ‘Lord Shiva’ (‘Rudra’ means ‘Shiva’ and ‘Aksh’ means
                          ‘tear’) with its medicinal and holistic properties. Coincidently, our practice is also in tune
                          with National Education Policy 2020. Followings are major objectives:</p>
                        <p>&nbsp;</p>
                        <ul class="list-style-7-unbold margin-30px-bottom">
