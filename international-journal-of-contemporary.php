                <h2>Guidelines for Authors</h2>
                <p>International Journal of Contemporary Research in Engineering and Technology invites academicians and
                  professionals to contribute research papers, articles, abstracts of doctoral dissertations, major
                  research project reports, case studies, comprehensive bibliography, and book reviews.</p>
                <p>The following are the guidelines for the authors: </p>
                <ul class="list-style-6-unbold">
                  <li class="mb-4 fs-6">The contribution must be original, neither published nor under consideration for
                    publication.</li>

                  <li class="mb-4 fs-6">The cover page should contain the title of the paper, author’s name,
                    designation, official
                    address,contact phone/fax number and the e-mail address. The next page should contain an abstract of
                    not more than 150 words, along with 5 key words. The main text should not contain the author’s name.
                  </li>

                  <li class="mb-4 fs-6">References should be given at the end of the manuscript and should contain only
                    those cited in the
                    text of the manuscript.</li>

                  <li class="mb-4 fs-6">References should be given in IEEE Format, i.e.

                    (i) E.N. Elnozahy, Y.M. Wang and D.B. Johnson, “A survey of Rollback-Recovery protocols in
                    Message-Passing systems,” ACM computing surveys, Vol. 24, No. 3, pp 375–408, 2002.
                    (ii) C.P. Agarwal, “Non linear fiber optics”, Academic Press, san Diego, 2006.

                  </li>

                  <li class="mb-4 fs-6">Notes (Footnotes) should be avoided. If necessary, then it should be indicated
                    by serial number in
                    the text (1, 2,...) at the end of the research paper on a separate sheet just before references.
                    Notes should not be mixed with references.</li>

                  <li class="mb-4 fs-6">Figures and tables should be numbered consecutively, in international numerals,
                    and should appear
                    soon after the text where they are cited first. The figures should be accommodated within two-thirds
                    of the A-4 size paper. All the figures and tables must be suitably captioned.</li>

                  <li class="mb-4 fs-6">Please check your manuscript for clarity, grammar, spelling, punctuation, and
                    consistency of
                    references to minimize editorial changes.</li>

                  <li class="mb-4 fs-6">The use of capitilisation should be kept to the minimum, except in case of
                    proper nouns, and
                    should be followed consistently.</li>

                  <li class="mb-4 fs-6">A manuscript should not be more than 10,000 words.</li>

                  <li class="mb-4 fs-6">The manuscript should be in double space; in 12-points font size, on A-4 size
                    paper, leaving 4 cms
                    margin on all sides, so as to facilitate editing and styling. All texts, including abstract,
                    quotations, notes and references should be typed in double-space.</li>

                  <li class="mb-4 fs-6">The contribution should be sent as an e-mail attachment to: ijcreat@gmail.com
                    with a copy to <a href="mailto:prajanag@gmail.com">prajanag@gmail.com</a> and a soft copy (in MS
                    Word format) is to
                    be sent by post/courier to the editor.</li>

                  <li class="mb-4 fs-6">The contributions received for publication shall be referred to two experts on
                    the subject, for
                    review.</li>

                  <li class="mb-4 fs-6">Proof for correction, if required, will be sent to the author underlined, unless
                    otherwise
                    indicated. Corrected proofs should be returned within a week.</li>

                  <li class="mb-4 fs-6">The forwarding letter must include a certificate by the author(s) to the effect
                    that the article
                    is original and an exclusive contribution to the IJCREAT and shall not be released for publication
                    elsewhere unless the Editor’s decision not to publish has been communicated to the author(s).</li>

                  <li class="mb-4 fs-6">The final decision on the acceptance or otherwise of the paper rests with the
                    Editorial Board, and
                    its publication depends entirely on the standard and relevance of the paper.</li>

                  <li class="mb-4 fs-6">The final draft may be subjected to editorial amendments to suit the Journal’s
                    requirements.</li>

                  <li class="mb-4 fs-6">The author will receive one copy of the Journal free of charge, soon after its
                    publication.</li>

                  <li class="mb-4 fs-6">The copyright of the articles and other material published in the Journal, shall
                    lie with the
                    publisher.</li>
                  <li class="mb-4 fs-6">The references to websites should be kept to the minimum. The date of accession
                    of the website
                    should be invariably mentioned within a bracket.</li>

                  <li class="mb-4 fs-6">All manuscripts are subject to blind review and are expected to meet the
                    standards of academic
                    excellence. Identities of reviewers will remain anonymous to the author(s).</li>
                  <li class="mb-4 fs-6">If the manuscript is accepted for publication, paper must not be published any
                    where without the
                    written permission of the editor.</li>
                  <li class="mb-4 fs-6">International Journal of Contemporary Research in Engineering and Technology
                    (IJCREAT) is a
                    biannual peer-reviewed journal of Shobhit University, Meerut which aims to publish original research
                    papers of high quality in the field of Engineering and Technology.</li>
                  <li class="mb-4 fs-6">Short communication on Applications and Testing are also invited for
                    publication.</li>
                </ul>
