                <p>Keeping in mind, the statement of James Russell Lowell that journals are the bees which carry the
                  quickening pollen from one mind to another, I have the pleasure to present the inaugural issue of the
                  ‘International Journal of Contemporary Research in Engineering and Technology’. I may say that the
                  emergence of Shobhit University at the sacred epicenter of the Ganges and the Yamuna doab make it as
                  unique as the confluence of the disparate and multidisciplinary researches in engineering and
                  technology being carried out here. The much awaited impetus in this inspirational and welcome effort
                  through an international journal on the subject under the auspices of the Academy of Sciences,
                  Engineering and Management: An Initiative of Shobhit Univrsity is a milestone for many reasons and I
                  would briefly delve on this.</p>
                <p>As technology is advancing, engineering and technology are coming of age in India, with newer
                  insights, abstractions, algorithms, hardware, and integrations. Since engineering and technology are
                  central to the advancement of our country, also being relevant to an increasing range of applications
                  and human welfare, it was important to launch this contemporary journal on the demand of researchers
                  in the region. No doubt scientists and engineers strive to combine engineering systems and the
                  advances in technology with mathematical and organizational tools to create complex models to better
                  understand reality. Any archival journal to publish and disseminate the abstractions, algorithms,
                  theory, methodologies, models, systems, and case studies that can be applied across and around the
                  globe will significantly advance efficiency, quality, productivity, and reliability of technology for
                  the welfare of human society. </p>
                <p>More than any other desired objectives, this journal will encourage young researchers to put in their
                  best foot forward as also introduce and integrate them to global scientific thoughts and precepts. The
                  inaugural issue had indeed been a difficult exercise so as to ensure the highest ii International
                  Journal of Contemporary Research in Engg. and Tech. Vol. 1, No. 1, 2011 standards of ethics and
                  excellence. Apart from a rigorous and uncompromising peer-based blind review process it was felt that
                  the quality and standard of the journal were necessary for its long-term success.</p>
                <p>Some of the very insightful papers and the exciting researches that appear in the inaugural issue
                  range from the crawlers to the hidden web resources, bio-engineering techniques and their
                  applications, software development and testing tools, material for transparent electrodes for solar
                  cell and odour sensing discrimination techniques are very contemporaneous and exciting work.</p>
                <p>‘In silico miRNAs Traget identification in Burma agrimony’ is a very futuristic work in
                  agri-informatics and genetic engineering that also happens to be the thrust area for research at
                  Shobhit University.</p>
                <p>A book review section at the end will introduce the recent literature, books and works that may be of
                  tremendous value to the engineering and technology community. In the inaugural issue it is a delight
                  to see the very timely and topical books on “Data Structures using C” by Prof. (Dr.) A.K. Sharma,
                  reviewed by Prof. (Dr.) J.P. Gupta, Former Vice-Chancellor, JIIT University. The book on “The Theory
                  of Computation” by Wayne Goddard has been exhaustively reviewed by Prof. (Dr.) Irene Sarkar. The book
                  on “Digital Integrated Circuits: A Design Perspective” by Jan M. Rabaey, Anantha Chandrakasan and
                  Borivoje Nikolic, now in the market has an insightful review by Prof. (Dr.) S. Sarkar whereas the one
                  on “Embedded System” by Kanta Rao, reviewed by Prof. (Dr.) B.K. Kaushik, IIT Roorkee. Visualized quite
                  some back this contemporary journal has now become a reality thanks to the vision of Hon’ble Pro
                  Chancellor Kunwar Shekhar ji and the efforts and hard work of Prof. (Dr.) R.P. Agarwal,
                  Vice-Chancellor alongwith their dedicated team have indeed burnt the midnight oil to make this
                  possible. The worth of the journal is to be measured by what you can carry away from it, so mentioned
                  James Bryce and I am confident that this maiden issue and the many more to come in posterity will hold
                  true on this score alone. The inaugural issue is proposed to be followed up by biannual publications
                  of the Journal that I am sure will be patronized by both the students and the scientific community and
                  will reach great heights in the days to come.</p>
